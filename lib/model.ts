// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token and not a wrapped, staked or
// bridged product of a token that already trades: the house watchlist's own rule, applied to the
// whole snapshot instead of only above its $50M floor. The watchlist's 40 slugs are all in it, and
// the 138 rankable protocols below the floor are the early rows the radar exists to find. A protocol
// is pre-token when its record carries no token (no CoinGecko id, no symbol); the live-token
// protocols are kept apart and shown with the market's own capitalisation, never mixed into the
// ranked board.
//
// Implied value follows only from the snapshot's own figures, never from a hand-kept list of names:
//
//   ratio      = the median market-cap-per-TVL of the live-token protocols in the same category
//                (at least five peers, else the snapshot-wide median): what the market already
//                pays per dollar of TVL for this kind of protocol
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   ageMult    = 0.8 + min(age_days, 1460) / 1460 x 0.4   (age unknown: 365 days)
//   implied    = round(tvl_usd x ratio x growthMult x ageMult)
//
// No protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  age_floor: number;
  age_range: number;
  age_days: number;
  unknown_age_days: number;
  category_peer_min: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 150,
  age_floor: 0.8,
  age_range: 0.4,
  age_days: 1460,
  unknown_age_days: 365,
  category_peer_min: 5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

